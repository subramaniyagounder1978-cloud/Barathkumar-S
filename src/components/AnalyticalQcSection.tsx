import { useState } from 'react';
import { ANALYTICAL_TRACES, type SpectrumId } from '../data/analytics';

const TRACE_TABS: Array<{ id: SpectrumId; label: string }> = [
  { id: 'hplc', label: 'HPLC-UV Chromatogram' },
  { id: 'nmr', label: '1H NMR Spectrum' },
  { id: 'sfc', label: 'Chiral SFC Trace' },
];

export function AnalyticalQcSection() {
  const [activeId, setActiveId] = useState<SpectrumId>('hplc');
  const trace = ANALYTICAL_TRACES[activeId];

  const svgW = 640;
  const svgH = 220;
  const padL = 40;
  const padR = 20;
  const padT = 24;
  const padB = 34;
  const innerW = svgW - padL - padR;
  const innerH = svgH - padT - padB;

  const toX = (xPct: number) => padL + (xPct / 100) * innerW;
  const toY = (yPct: number) => padT + innerH - (yPct / 100) * innerH;

  const polylinePath = trace.points
    .map((pt, i) => `${i === 0 ? 'M' : 'L'} ${toX(pt.x).toFixed(1)} ${toY(pt.y).toFixed(1)}`)
    .join(' ');

  return (
    <section id="analytical-qc" className="py-16 lg:py-20 bg-white border-b border-slate-200">
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="flex flex-col lg:flex-row lg:items-end justify-between gap-6 mb-8">
          <div className="max-w-2xl">
            <p className="text-xs font-mono tracking-wide text-slate-500 mb-2">
              Certificate of Analysis &amp; Release
            </p>
            <h2
              className="text-2xl sm:text-3xl font-bold tracking-tight text-slate-900"
              style={{ textWrap: 'balance' }}
            >
              Empirical analytical verification on every batch
            </h2>
            <p className="mt-2 text-sm text-slate-600">
              Inspect representative release spectra generated by our analytical chemistry suite.
              All deliverables ship with raw FID/PDA data files and signed CoA documentation.
            </p>
          </div>

          <div
            role="tablist"
            aria-label="Analytical spectrum selector"
            className="flex flex-wrap items-center gap-1.5 p-1 bg-slate-100 border border-slate-200 rounded-lg"
          >
            {TRACE_TABS.map((tab) => {
              const active = tab.id === activeId;
              return (
                <button
                  key={tab.id}
                  type="button"
                  role="tab"
                  aria-selected={active}
                  onClick={() => setActiveId(tab.id)}
                  className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 cursor-pointer ${
                    active
                      ? 'bg-white text-slate-900 shadow-xs'
                      : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  {tab.label}
                </button>
              );
            })}
          </div>
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-stretch">
          {/* SVG Trace Viewer */}
          <div className="lg:col-span-7 bg-[#F8FAFC] border border-slate-200 rounded-lg p-5 flex flex-col justify-between">
            <div className="flex flex-wrap items-start justify-between gap-4 mb-4">
              <div>
                <p className="text-xs font-mono text-slate-500">{trace.sampleCode}</p>
                <h3 className="text-base font-semibold text-slate-900 mt-0.5">{trace.title}</h3>
                <p className="text-xs text-slate-500 mt-0.5">{trace.instrument}</p>
              </div>
              <div className="text-right">
                <span className="block text-[11px] font-mono text-slate-500">
                  {trace.metricLabel}
                </span>
                <span className="text-2xl font-bold font-mono tabular-nums text-[#1D4ED8]">
                  {trace.metricValue}
                </span>
              </div>
            </div>

            <div className="bg-white border border-slate-200 rounded-md p-3">
              <svg
                viewBox={`0 0 ${svgW} ${svgH}`}
                className="w-full h-56 select-none"
                role="img"
                aria-label={trace.title}
              >
                {/* Horizontal gridlines */}
                {[0, 25, 50, 75, 100].map((tick) => {
                  const y = toY(tick);
                  return (
                    <line
                      key={tick}
                      x1={padL}
                      y1={y}
                      x2={svgW - padR}
                      y2={y}
                      stroke="#F1F5F9"
                      strokeWidth="1"
                    />
                  );
                })}

                {/* X-axis baseline */}
                <line
                  x1={padL}
                  y1={padT + innerH}
                  x2={svgW - padR}
                  y2={padT + innerH}
                  stroke="#CBD5E1"
                  strokeWidth="1"
                />

                {/* X-axis tick labels */}
                {trace.xTicks.map((tickLabel, idx) => {
                  const x = padL + (idx / (trace.xTicks.length - 1)) * innerW;
                  return (
                    <g key={tickLabel}>
                      <line
                        x1={x}
                        y1={padT + innerH}
                        x2={x}
                        y2={padT + innerH + 4}
                        stroke="#94A3B8"
                        strokeWidth="1"
                      />
                      <text
                        x={x}
                        y={padT + innerH + 17}
                        textAnchor="middle"
                        className="fill-slate-500 text-[10px] font-mono"
                      >
                        {tickLabel}
                      </text>
                    </g>
                  );
                })}

                {/* Trace line */}
                <path
                  d={polylinePath}
                  fill="none"
                  stroke="#0F172A"
                  strokeWidth="1.75"
                  strokeLinejoin="round"
                />

                {/* Peak annotations */}
                {trace.annotations.map((ann) => {
                  const ax = toX(ann.x);
                  const ay = toY(ann.y);
                  const anchor = ann.x > 82 ? 'end' : ann.x < 18 ? 'start' : 'middle';
                  return (
                    <g key={ann.text}>
                      <circle cx={ax} cy={ay} r="2.5" fill="#1D4ED8" />
                      <text
                        x={ax}
                        y={Math.max(14, ay - 7)}
                        textAnchor={anchor}
                        className="fill-[#1D4ED8] text-[10px] font-mono font-medium"
                      >
                        {ann.text}
                      </text>
                    </g>
                  );
                })}

                <text
                  x={padL + innerW / 2}
                  y={svgH - 3}
                  textAnchor="middle"
                  className="fill-slate-400 text-[10px] font-mono"
                >
                  {trace.xAxisLabel}
                </text>
              </svg>
            </div>
          </div>

          {/* Peak Integration Table */}
          <div className="lg:col-span-5 border border-slate-200 rounded-lg overflow-hidden bg-white flex flex-col justify-between">
            <div>
              <div className="px-5 py-3.5 bg-[#F8FAFC] border-b border-slate-200 flex items-center justify-between">
                <h3 className="text-sm font-semibold text-slate-900">Peak Integration Report</h3>
                <span className="text-xs font-mono text-slate-500">Status: Release Passed</span>
              </div>

              <div className="overflow-x-auto">
                <table className="w-full text-left border-collapse">
                  <thead>
                    <tr className="border-b border-slate-200 text-[11px] font-mono text-slate-500 bg-slate-50/60">
                      <th className="py-2.5 px-4 font-medium">Signal</th>
                      <th className="py-2.5 px-3 font-medium">Position</th>
                      <th className="py-2.5 px-3 font-medium text-right">Area / H</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100 text-xs">
                    {trace.peaks.map((peak) => (
                      <tr key={peak.label} className="hover:bg-slate-50/60">
                        <td className="py-3 px-4">
                          <div className="font-semibold text-slate-900">{peak.label}</div>
                          <div className="text-slate-500 mt-0.5">{peak.assignment}</div>
                        </td>
                        <td className="py-3 px-3 font-mono tabular-nums text-slate-700 whitespace-nowrap">
                          {peak.position}
                        </td>
                        <td className="py-3 px-3 text-right font-mono font-semibold tabular-nums text-slate-900 whitespace-nowrap">
                          {peak.areaOrIntegral}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>

            <div className="p-5 bg-[#F8FAFC] border-t border-slate-200 text-xs text-slate-600 space-y-1.5">
              <div className="flex justify-between font-mono tabular-nums">
                <span className="text-slate-500">Residual Palladium (ICP-MS)</span>
                <span className="text-slate-900 font-medium">&lt; 2.4 ppm (Spec &lt; 10 ppm)</span>
              </div>
              <div className="flex justify-between font-mono tabular-nums">
                <span className="text-slate-500">Water Content (Karl Fischer)</span>
                <span className="text-slate-900 font-medium">0.04 wt% (Spec &lt; 0.20 wt%)</span>
              </div>
              <div className="flex justify-between font-mono tabular-nums">
                <span className="text-slate-500">Residual Solvents (GC-HS)</span>
                <span className="text-slate-900 font-medium">ICH Q3C Class 2/3 Compliant</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}
